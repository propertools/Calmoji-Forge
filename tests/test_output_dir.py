def test_the_default_output_dir_is_output_year_alignment(tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)

    main(["--year=2027"])
    main(["--year=2027", "--calendar-alignment=calendar"])
    main(["--year=2028", "--calendar-alignment=calendar"])

    assert (tmp_path / "output" / "2027" / "academic" / "seasons_2027.ics").is_file()
    assert (tmp_path / "output" / "2027" / "calendar" / "seasons_2027.ics").is_file()
    assert (tmp_path / "output" / "2028" / "calendar" / "seasons_2028.ics").is_file()
    # runs for different years and alignments no longer mix
    assert len(focus_files(tmp_path / "output" / "2027" / "academic")) == 12
    assert len(focus_files(tmp_path / "output" / "2027" / "calendar")) == 12
    assert not (tmp_path / "output" / "seasons_2027.ics").exists()


def test_the_default_is_computed_from_year_and_alignment():
    assert default_output_dir(2027, "academic") == Path("output") / "2027" / "academic"
    assert parse_args(["--year=2027"]).output_dir is None
    assert parse_args(["--year=2027", "--output-dir=somewhere"]).output_dir == Path("somewhere")


def test_help_describes_the_default_and_the_marker(capsys):
    with pytest.raises(SystemExit):
        parse_args(["--help"])
    text = " ".join(capsys.readouterr().out.split())
    assert "output/<year>/<alignment>/" in text
    assert ".calmoji-output" in text
